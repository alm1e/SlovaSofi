// Run with: node --expose-internals tools/build-locales.cjs
// Extends existing locale tables without changing lesson content or storage keys.
const fs = require('node:fs');
const acorn = require('internal/deps/acorn/acorn/dist/acorn');
const source = JSON.parse(fs.readFileSync('tools/locale-source.json', 'utf8'));
const rows = fs.readFileSync('tools/locales.tsv', 'utf8').trimEnd().split(/\r?\n/).map(line => line.split('\t').map(value => value.replace(/\\n/g, '\n')));
if (rows.length !== source.length || rows.some(row => row.length !== 2)) throw Error(`Locale row mismatch: ${rows.length}/${source.length}`);
const dictionaries = Object.fromEntries(['sk', 'kk'].map((lang, column) => [lang, Object.fromEntries(source.map((text, index) => [text, rows[index][column]]))]));
for (const row of fs.readFileSync('tools/locale-extras.tsv', 'utf8').trimEnd().split(/\r?\n/).map(line => line.split('\t'))) {
    dictionaries.sk[row[0]] = row[1]; dictionaries.kk[row[0]] = row[2];
}
const runtime = `/* Shared Slovak and Kazakh UI translations. Generated by tools/build-locales.cjs. */
(function (root) {
    'use strict';
    const dictionaries = ${JSON.stringify(dictionaries, null, 2)};
    const cache = { sk: new WeakMap(), kk: new WeakMap() };
    function translate(value, language) {
        if (typeof value === 'string') return dictionaries[language]?.[value] ?? value;
        if (value && typeof value === 'object' && cache[language]?.has(value)) return cache[language].get(value);
        if (Array.isArray(value)) return value.map(item => translate(item, language));
        if (value && typeof value === 'object') {
            const result = Object.fromEntries(Object.entries(value).map(([key, item]) => [key, translate(item, language)]));
            cache[language]?.set(value, result);
            return result;
        }
        return value;
    }
    function locales(table) {
        return new Proxy(table, {
            get(target, language, receiver) {
                if ((language === 'sk' || language === 'kk') && !Object.hasOwn(target, language)) return translate(target.en, language);
                return Reflect.get(target, language, receiver);
            }
        });
    }
    root.SlovaI18n = { locales, translate, languages: ['ua', 'ru', 'en', 'sk', 'kk'] };
    if (typeof document !== 'undefined') {
        const names = { ua: 'Українська', ru: 'Русский', en: 'English', sk: 'Slovenčina', kk: 'Қазақша' };
        document.addEventListener('DOMContentLoaded', () => {
            let saved;
            try { saved = localStorage.getItem('siteLanguage'); } catch {}
            if (names[saved]) document.documentElement.lang = saved === 'ua' ? 'uk' : saved;
            document.querySelectorAll('[data-lang]').forEach(button => {
                if (names[button.dataset.lang]) {
                    button.setAttribute('aria-label', names[button.dataset.lang]);
                    button.title = names[button.dataset.lang];
                }
            });
        });
        document.addEventListener('click', event => {
            const language = event.target.closest?.('[data-lang]')?.dataset.lang;
            if (names[language]) document.documentElement.lang = language === 'ua' ? 'uk' : language;
        });
    }
})(globalThis);
`;
fs.writeFileSync('assets/js/locales.js', runtime);
function transform(code) {
    const edits = [];
    function walk(node, parent) {
        if (!node || typeof node !== 'object') return;
        const stringBranches = value => value?.type === 'Literal' && typeof value.value === 'string' || value?.type === 'ConditionalExpression' && stringBranches(value.consequent) && stringBranches(value.alternate);
        if (node.type === 'ConditionalExpression' && node.test.type === 'BinaryExpression' && ['currentLanguage', 'language'].includes(node.test.left?.name) && stringBranches(node) && !(parent?.type === 'ConditionalExpression') && !(parent?.type === 'CallExpression' && code.slice(parent.callee.start, parent.callee.end) === 'SlovaI18n.translate')) {
            edits.push([node.start, 'SlovaI18n.translate('], [node.end, `, ${node.test.left.name})`]);
        }
        if (node.type === 'ObjectExpression') {
            const keys = node.properties.map(p => p.key?.name || p.key?.value);
            if (keys.includes('en') && (keys.includes('ua') || keys.includes('ru')) && !(parent?.type === 'CallExpression' && code.slice(parent.callee.start, parent.callee.end) === 'SlovaI18n.locales')) {
                edits.push([node.start, 'SlovaI18n.locales('], [node.end, ')']);
            }
        }
        for (const value of Object.values(node)) {
            if (Array.isArray(value)) value.forEach(child => walk(child, node));
            else if (value && typeof value === 'object') walk(value, node);
        }
    }
    walk(acorn.parse(code, { ecmaVersion: 'latest', sourceType: 'script' }));
    for (const [offset, text] of edits.sort((a,b) => b[0] - a[0])) code = code.slice(0,offset) + text + code.slice(offset);
    return code.replaceAll('["ua", "ru", "en"]', '["ua", "ru", "en", "sk", "kk"]');
}
for (const file of fs.readdirSync('assets/js').filter(file => file.endsWith('.js') && !file.includes('.test.') && file !== 'locales.js')) {
    const path = `assets/js/${file}`;
    const before = fs.readFileSync(path, 'utf8');
    const after = transform(before);
    if (after !== before) fs.writeFileSync(path, after);
}
for (const file of fs.readdirSync('.').filter(file => file.endsWith('.html'))) {
    let html = fs.readFileSync(file, 'utf8');
    html = html.replace(/(<script(?:\s[^>]*)?>)([\s\S]*?)(<\/script>)/g, (all, open, code, close) => open + transform(code) + close);
    html = html.replace(/\s*<script src="assets\/js\/locales.js"><\/script>/g, '');
    html = html.replace(/(<meta charset="UTF-8">)/i, '$1\n    <script src="assets/js/locales.js"></script>');
    if (!html.includes('data-lang="sk"')) html = html.replace(/(<button\b[^>]*data-lang="en"[^>]*>[\s\S]*?<\/button>)/g, button => button + '\n' + button.replace('data-lang="en"', 'data-lang="sk"').replace('>EN<', '>SK<').replace('>en<', '>sk<') + '\n' + button.replace('data-lang="en"', 'data-lang="kk"').replace('>EN<', '>ҚАЗ<').replace('>en<', '>kk<'));
    html = html.replace(/data-lang="sk"([^>]*?)aria-label="English"/g, 'data-lang="sk"$1aria-label="Slovenčina"').replace(/data-lang="kk"([^>]*?)aria-label="English"/g, 'data-lang="kk"$1aria-label="Қазақша"');
    html = html.replace(/data-lang="sk" onclick="changeLanguage\('en'\)"/g, 'data-lang="sk" onclick="changeLanguage(\'sk\')"').replace(/data-lang="kk" onclick="changeLanguage\('en'\)"/g, 'data-lang="kk" onclick="changeLanguage(\'kk\')"');
    fs.writeFileSync(file, html);
}
